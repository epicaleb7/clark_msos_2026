// G := SemidirectProduct(ZZmod2to9, D8, conjugation);
rho := hom<Salal -> Salal | [c_alal,f_alal,i_alal,b_alal,e_alal,h_alal,a_alal,d_alal,g_alal]>; // rotate cw
sigma := hom<Salal -> Salal | [g_alal,h_alal,i_alal,d_alal,e_alal,f_alal,a_alal,b_alal,c_alal]>; // flip about x-axis
tauVec := [hom<Salal -> Salal | [j eq i select -Salal.j else Salal.j : j in [1..9]]> : i in [1..9]];

// action of G on an ideal:
ActOnIdealQQalal := function(phi, J)
    gens := Generators(J);
    new_gens := [Salal ! phi(f) : f in gens ];
    return Ideal(new_gens);
end function;

GOrbitQQalal := function(P)
    SymmetriesOfPList := [];
    for rhoPower in [0..3] do
        for sigmaPower in [0..1] do
            // only 8 of the 9 sign flips: flipping all 9 fixes every homogeneous ideal
            for tauPowers in CartesianProduct([[0,1] : i in [1..8]]) do
            // construct permutation
            tauComposed := &*[tauVec[i]^tauPowers[i] : i in [1..8]];
            phi_g := tauComposed * sigma^sigmaPower * rho^rhoPower; // covers all 2048 elements acting on P^8
            // compute dMap (dummy map) of the ideal P
            phi_g_P := ActOnIdealQQalal(phi_g, P);
            Append(~SymmetriesOfPList, phi_g_P);
            end for;
        end for;
    end for;
    return SymmetriesOfPList;
end function;

hardcodedsizeoforbitcountieexpectedamximumsizeofGIMS := 1000;

ReduceByGInQQalal := function(Plist)
    error if #Plist gt 0 and Generic(Plist[1]) cmpne Salal,
        "ReduceByGInQQalal expects ideals of Salal (over QQalal).";
    GenericIdealsModSymmetry := [];
    OrbitCount := [1: i in [0..hardcodedsizeoforbitcountieexpectedamximumsizeofGIMS]]; // otherwise the code is more complex lol
    for P in Plist do
        // compute some symmetry transformations of my ideal
        SymmetriesOfP := GOrbitQQalal(P);
        // if one element of SymmetriesOfP in GenericIdealsModSymmetry
        if exists(IndexInGIMSOfsymmetricP){
            Index(GenericIdealsModSymmetry,symmetricP) :
            symmetricP in SymmetriesOfP |
            symmetricP in GenericIdealsModSymmetry
            } then
            OrbitCount[IndexInGIMSOfsymmetricP] +:= 1;
        else // it's a new ideal!
            Append(~GenericIdealsModSymmetry, P);
        end if;
    end for;
    return GenericIdealsModSymmetry, OrbitCount[1..#GenericIdealsModSymmetry];
end function;
// Idea of above exists(){} thing: loop through elements of the G orbit of P. If any occurs also in the GIMS we've already seen, then update the OrbitCount at that index by +1.

// Is V(J) empty in P^8? Projective Nullstellensatz: iff Radical(J) is (1) or the irrelevant ideal (a,...,i).
// (Testing J eq (1) is NOT enough: J is generated by forms of positive degree, so 1 is never in J.)
IsProjEmpty := function(J)
    RadJ := Radical(J);
    return RadJ eq ideal<Salal|1> or RadJ eq ideal<Salal|[a_alal,b_alal,c_alal,d_alal,e_alal,f_alal,g_alal,h_alal,i_alal]>;
end function;

